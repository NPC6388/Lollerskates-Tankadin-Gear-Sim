#!/usr/bin/env node
// Generate golden parity fixtures for the Lua engine port.
//
// Runs the JS evaluateSet() (the source of truth) over the canonical sheet-parity inputs and
// writes them — inputs + FULL outputs — as a Lua-loadable table at test/lua/fixtures.lua. The
// Lua parity runner (test/lua/eval_parity.lua) loads the ported engine and asserts it reproduces
// these numbers within epsilon, so the addon math can't silently drift from the website.
//
// The inputs mirror test/sheet-parity.test.js (transcribed from the user's original tank
// spreadsheet); keep them in sync if that fixture changes.

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { evaluateSet } from '../src/character.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../test/lua');
const outFile = resolve(outDir, 'fixtures.lua');

// Canonical inputs (mirror test/sheet-parity.test.js COLUMNS + the under-defended case).
const INPUTS = {
  Norms: { defenseSkill: 451, resilienceRating: 69, missPct: 9.04, dodgePct: 10.73, parryPct: 14.04, blockPct: 20.07, hsBlockBonus: 30, armor: 14000, health: 12000 },
  Block: { defenseSkill: 490, resilienceRating: 0, missPct: 10.6, dodgePct: 12.93, parryPct: 16.61, blockPct: 40.91, hsBlockBonus: 35.32, armor: 16000, health: 11000 },
  Heroies: { defenseSkill: 501, resilienceRating: 0, missPct: 11.04, dodgePct: 16.59, parryPct: 16.04, blockPct: 27.15, hsBlockBonus: 30, armor: 15139, health: 13000, spellPower: 639, blockValue: 137 },
  RaidThreat: { defenseSkill: 486, resilienceRating: 11, missPct: 10.44, dodgePct: 16.88, parryPct: 16.67, blockPct: 23.12, hsBlockBonus: 35.32, armor: 15139, health: 12500, spellPower: 709 },
  UnderDefended: { defenseSkill: 400, resilienceRating: 0, missPct: 8, dodgePct: 10, parryPct: 12, blockPct: 18 },
};

// Only the numeric/boolean scalars evaluateSet returns (skip the nested _raw etc — there are none).
const luaScalar = (v) => {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return String(v); // numbers: full precision
};

const luaTable = (obj, indent) => {
  const pad = ' '.repeat(indent);
  const inner = Object.entries(obj)
    .map(([k, v]) => `${pad}  ${k} = ${luaScalar(v)},`)
    .join('\n');
  return `{\n${inner}\n${pad}}`;
};

const cases = Object.entries(INPUTS).map(([name, input]) => {
  const out = evaluateSet(input);
  return `  {\n    name = ${JSON.stringify(name)},\n    input = ${luaTable(input, 4)},\n    expected = ${luaTable(out, 4)},\n  },`;
});

const banner =
  '-- GENERATED by bin/gen-fixtures.mjs — do not edit by hand.\n' +
  '-- Golden evaluateSet() outputs from the JS engine (src/character.js), the source of truth.\n' +
  '-- Regenerate: npm run gen-fixtures\n\n';

const body = `return {\n${cases.join('\n')}\n}\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, banner + body);
console.log(`Wrote ${Object.keys(INPUTS).length} fixtures -> ${outFile}`);
