#!/usr/bin/env node
// Generate golden parity fixtures for the ported forward model (engine/Model.lua + CharacterData.lua).
//
// Runs the JS aggregate()/talentsFromRanks() (source of truth) over representative item selections ×
// option sets and writes inputs + outputs to test/lua/model_fixtures.lua. The Lua runner
// (model_parity.lua) loads the generated CharacterData.lua + hand-ported Model.lua and asserts it
// reproduces these within epsilon — so the addon's forward model can't drift from the website's.
//
// Regenerate: npm run gen-model-fixtures

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { aggregate, talentsFromRanks, BUFFS } from '../src/model.js';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../test/lua/model_fixtures.lua');

// A couple of item selections (each item = { stats }).
const GEAR = [
  { stats: { stamina: 45, strength: 22, defenseRating: 20, dodgeRating: 18, blockRating: 12, armor: 800, spellDamage: 30 } },
  { stats: { stamina: 30, agility: 14, parryRating: 16, blockValue: 25, spellDamage: 18, spellHitRating: 10, spellCritRating: 8, resilienceRating: 12 } },
  { stats: { stamina: 38, intellect: 20, defenseRating: 15, hitRating: 14, expertiseRating: 6, spellDamage: 22, armor: 1400 } },
];

// aggregate() cases exercising kings, MotW buffs, talent overrides, flatArmor, hsBlockBonus.
const CASES = [
  { name: 'baseNoOpts', items: [], opts: {} },
  { name: 'gearUnbuffed', items: GEAR, opts: {} },
  { name: 'gearKings', items: GEAR, opts: { kings: true } },
  { name: 'gearKingsMotW', items: GEAR, opts: { kings: true, buffs: BUFFS.markOfTheWild } },
  { name: 'gearScrollHS', items: GEAR, opts: { kings: true, flatArmor: 301, hsBlockBonus: 35.32 } },
  { name: 'gearRetTalents', items: GEAR, opts: { kings: true, talents: talentsFromRanks({ Anticipation: 0, Deflection: 3, Toughness: 0, 'Improved Righteous Fury': 0 }) } },
];

// talentsFromRanks() cases (rank map -> talent modifiers).
const RANKS = [
  { name: 'defaultBuild', ranks: {} },
  { name: 'fullProt', ranks: { 'Sacred Duty': 2, 'Combat Expertise': 5, Toughness: 5, Anticipation: 5, Deflection: 5, Precision: 3, 'Improved Righteous Fury': 3 } },
  { name: 'pvpish', ranks: { Anticipation: 0, Deflection: 3, Toughness: 0, 'Improved Righteous Fury': 0, Precision: 2 } },
];

const luaScalar = (v) => (typeof v === 'boolean' ? (v ? 'true' : 'false') : v == null ? 'nil' : String(v));
const luaFlat = (obj, indent) => {
  const pad = ' '.repeat(indent);
  const inner = Object.entries(obj).map(([k, v]) => `${pad}  ${k} = ${luaScalar(v)},`).join('\n');
  return `{\n${inner}\n${pad}}`;
};
const luaItems = (items, indent) => {
  const pad = ' '.repeat(indent);
  const inner = items.map((it) => `${pad}  { stats = ${luaFlat(it.stats, indent + 2)} },`).join('\n');
  return items.length ? `{\n${inner}\n${pad}}` : '{}';
};
// Only the scalar outputs (skip the nested _raw — its keys are covered by the stat-summed fields).
const scalarsOf = (obj) => Object.fromEntries(Object.entries(obj).filter(([, v]) => typeof v !== 'object'));

const aggCases = CASES.map((c) => {
  const out = scalarsOf(aggregate(c.items, c.opts));
  const optsLua = `{ ${Object.entries(c.opts).map(([k, v]) => `${k} = ${typeof v === 'object' ? luaFlat(v, 4) : luaScalar(v)}`).join(', ')} }`;
  return `  { name = ${JSON.stringify(c.name)}, items = ${luaItems(c.items, 4)}, opts = ${optsLua}, expected = ${luaFlat(out, 4)} },`;
}).join('\n');

const talentCases = RANKS.map((c) =>
  `  { name = ${JSON.stringify(c.name)}, ranks = ${luaFlat(c.ranks, 4)}, expected = ${luaFlat(talentsFromRanks(c.ranks), 4)} },`
).join('\n');

const banner =
  '-- GENERATED by bin/gen-model-fixtures.mjs — do not edit by hand.\n' +
  '-- Golden aggregate()/talentsFromRanks() outputs from the JS forward model (source of truth).\n' +
  '-- Regenerate: npm run gen-model-fixtures\n\n';

const body = `return {\n  aggregate = {\n${aggCases}\n  },\n  talents = {\n${talentCases}\n  },\n}\n`;

writeFileSync(outFile, banner + body);
console.log(`Wrote ${outFile}`);
