#!/usr/bin/env node
// Generate golden parity fixtures for the ported scoring core (engine/Scoring.lua + Weights.lua).
//
// Runs the JS score()/blendScale() (source of truth) over representative stat blocks × scales and
// writes inputs + outputs to test/lua/scoring_fixtures.lua. The Lua runner (scoring_parity.lua)
// loads the generated Weights.lua + hand-ported Scoring.lua and asserts it reproduces these within
// epsilon — so the addon's scoring can't drift from the website's.
//
// Regenerate: npm run gen-scoring-fixtures

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { SCALES, PARTS, blendScale } from '../src/weights.js';
import { score } from '../src/scoring.js';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../test/lua/scoring_fixtures.lua');

// Representative stat blocks (mixed threat/survival itemization + sockets).
const BLOCKS = {
  ThreatPiece: { stamina: 18, strength: 20, spellDamage: 26, spellHitRating: 15, spellCritRating: 14, blockRating: 8, redSockets: 1, yellowSockets: 1 },
  SurvivalPiece: { stamina: 34, agility: 12, defenseRating: 24, dodgeRating: 20, parryRating: 15, blockValue: 12, blueSockets: 1, metaSockets: 1 },
  MixedSet: { stamina: 220, strength: 120, agility: 60, intellect: 80, defenseRating: 140, dodgeRating: 90, parryRating: 70, blockRating: 60, blockValue: 90, hitRating: 45, expertiseRating: 22, spellDamage: 480, spellHitRating: 88, spellCritRating: 40, health: 300, armor: 15000, resilienceRating: 27, metaSockets: 1, redSockets: 6, yellowSockets: 4, blueSockets: 3 },
};

// Ratios that build the four in-game goal scales (mirror weights.js:GOAL_SCALES).
const RATIOS = {
  raidThreat: { threat: 2, sta: 1 },
  survival: { ehp: 2, threat: 1 },
  aoeThreat: { aoeThreat: 2, sta: 1 },
  balanced2: { ehp: 1, threat: 1 },
};

const luaScalar = (v) => (typeof v === 'boolean' ? (v ? 'true' : 'false') : v == null ? 'nil' : String(v));
const luaTable = (obj, indent) => {
  const pad = ' '.repeat(indent);
  const inner = Object.entries(obj).map(([k, v]) => `${pad}  ${k} = ${luaScalar(v)},`).join('\n');
  return `{\n${inner}\n${pad}}`;
};

// 1. score(block, namedScale) for every block × every named scale.
const scaleScores = Object.entries(BLOCKS).map(([bn, block]) => {
  const perScale = Object.keys(SCALES).map((sn) => `      ${sn} = ${score(block, SCALES[sn])},`).join('\n');
  return `  { block = ${JSON.stringify(bn)}, stats = ${luaTable(block, 4)},\n    scores = {\n${perScale}\n    } },`;
}).join('\n');

// 2. blendScale(ratio) — the full blended scale table, to compare key-by-key.
const blends = Object.entries(RATIOS).map(([name, ratio]) =>
  `  { name = ${JSON.stringify(name)}, ratio = ${luaTable(ratio, 4)}, scale = ${luaTable(blendScale(ratio), 4)} },`
).join('\n');

// 3. score(block, blendScale(ratio)) — end-to-end (blend then score).
const blendScores = Object.entries(BLOCKS).map(([bn, block]) => {
  const per = Object.entries(RATIOS).map(([rn, ratio]) => `      ${rn} = ${score(block, blendScale(ratio))},`).join('\n');
  return `  { block = ${JSON.stringify(bn)}, scores = {\n${per}\n    } },`;
}).join('\n');

const banner =
  '-- GENERATED by bin/gen-scoring-fixtures.mjs — do not edit by hand.\n' +
  '-- Golden score()/blendScale() outputs from the JS scoring core (source of truth).\n' +
  '-- Regenerate: npm run gen-scoring-fixtures\n\n';

const body =
  `return {\n` +
  `  scaleScores = {\n${scaleScores}\n  },\n` +
  `  blends = {\n${blends}\n  },\n` +
  `  blendScores = {\n${blendScores}\n  },\n` +
  `}\n`;

writeFileSync(outFile, banner + body);
console.log(`Wrote ${outFile}`);
